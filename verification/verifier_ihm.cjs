const {chromium} = require('playwright');
const baseUrl = (process.env.FRONTEND_URL || 'http://localhost:5000').replace(/\/$/, '');
(async()=>{
 const browser = await chromium.launch({headless:true, ...(process.env.BROWSER_PATH ? {executablePath:process.env.BROWSER_PATH} : {})});
 const page = await browser.newPage();
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 const api=[]; page.on('request',r=>{if(r.url().includes('/api/'))api.push(r.url())});
 await page.goto(baseUrl + '/ordinateurs');
 await page.waitForURL('**/login');
 await page.locator('#login').fill('inconnu');
 await page.getByRole('button',{name:'Se connecter'}).click();
 await page.getByText("Cet utilisateur n'existe pas.").waitFor();
 await page.locator('#login').fill('user2');
 await page.getByRole('button',{name:'Se connecter'}).click();
 await page.waitForURL(baseUrl + '/');
 await page.getByRole('link',{name:'Ordinateurs',exact:true}).click();
 await page.locator('tbody tr').first().waitFor();
 if(await page.locator('tbody tr').count()<5)throw Error('Liste ordinateurs incomplète');
 await page.reload();
 await page.locator('tbody tr').first().waitFor();
 await page.locator('#devise').selectOption('USD');
 await page.waitForFunction(()=>document.querySelector('tbody tr td:nth-child(3)')?.textContent==='USD');
 await page.getByRole('link',{name:'Réparations',exact:true}).click();
 await page.locator('tbody tr').first().waitFor();
 if(await page.getByRole('button',{name:'Simuler cinq réparations'}).count()) throw Error('Bouton Admin visible au gestionnaire');
 await page.getByRole('button',{name:'Déconnexion'}).click();
 await page.waitForURL(baseUrl + '/');
 if(await page.evaluate(()=>sessionStorage.getItem('jwtToken'))) throw Error('Token conservé après déconnexion');
 await page.goto(baseUrl + '/reparations'); await page.waitForURL('**/login');
 await page.locator('#login').fill('user1'); await page.getByRole('button',{name:'Se connecter'}).click();
 await page.waitForURL(baseUrl + '/');
 await page.getByRole('link',{name:'Réparations',exact:true}).click();
 await page.getByRole('button',{name:'Simuler cinq réparations'}).waitFor();
 await page.screenshot({path:process.env.SCREENSHOT_PATH || 'verification/interface.png',fullPage:true});
 if(api.some(u=>!u.startsWith('http://localhost:5010/')))throw Error('Appel direct hors Gateway');
 if(errors.length)throw Error(errors.join('\n'));
 console.log('IHM validée : redirection, login inconnu, connexion, session après rechargement, devises, listes, rôles et déconnexion. Tous les appels API passent par 5010.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
